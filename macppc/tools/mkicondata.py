#!/usr/bin/env python3
"""Turns a PNG into a C array the binary can carry.

C has no include_bytes!, which is what the Rust ports use to embed the icon
(src/icon.rs). This writes the equivalent header; the Makefile runs it into
build/ so nothing generated is ever checked in.

The embedded copy is only for running the binary *outside* an .app bundle -
straight out of build/ - where there is no Info.plist for LaunchServices to read
CFBundleIconFile from and the Dock would otherwise show the generic executable
icon. See src/icon.c.

    tools/mkicondata.py packaging/rworldradio-128.png build/icon_png.h
"""

import os
import sys


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: mkicondata.py <in.png> <out.h>\n")
        return 2

    source, out_path = argv[1], argv[2]
    with open(source, "rb") as handle:
        data = handle.read()

    lines = []
    for offset in range(0, len(data), 12):
        row = data[offset:offset + 12]
        lines.append("    " + " ".join("0x%02X," % byte for byte in row))

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w") as handle:
        handle.write(
            "/* Generated by tools/mkicondata.py from %s - do not edit. */\n"
            "#ifndef RWR_ICON_PNG_H\n"
            "#define RWR_ICON_PNG_H\n"
            "\n"
            "static const unsigned char RWR_ICON_PNG[] = {\n"
            "%s\n"
            "};\n"
            "\n"
            "#endif\n" % (os.path.basename(source), "\n".join(lines))
        )

    sys.stderr.write("mkicondata: %s - %d bytes from %s\n"
                     % (out_path, len(data), source))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
